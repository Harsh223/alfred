def pseudo(label, value):
    key = (label, value)
    if key not in vault:
        if label == "PERSON" and value in cust_names:
            p = f"<CLIENT_{int(cust_names[value]['customer_id'][3:]):04d}>"
        else:
            counters[label] = counters.get(label, 0) + 1; p = f"<{PREFIX[label]}_{counters[label]:04d}>"
        vault[key] = p
    return vault[key]
def anonymise(text, spans):
    out, last = [], 0
    for s in sorted(spans, key=lambda s: s["start"]):
        out.append(text[last:s["start"]]); out.append(pseudo(s["label"], s["value"])); last = s["end"]
    return "".join(out + [text[last:]])
