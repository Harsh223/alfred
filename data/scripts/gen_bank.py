# ---------------------------------------------------------------- span builder
def build(parts):
    """parts: str or (label, value). Returns text, spans."""
    out, spans, pos = [], [], 0
    for p in parts:
        if isinstance(p, tuple):
            lab, val = p; val = str(val)
            spans.append({"start": pos, "end": pos + len(val), "label": lab, "value": val})
            out.append(val); pos += len(val)
        else:
            out.append(p); pos += len(p)
    return "".join(out), spans

