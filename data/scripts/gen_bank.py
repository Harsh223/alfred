def card():
    d = [4] + [R.randint(0, 9) for _ in range(14)]
    s = sum(x if i % 2 else sum(divmod(2 * x, 10)) for i, x in enumerate(reversed(d)))  # luhn on 15 then check
    chk = (10 - (sum((x if i % 2 == 0 else sum(divmod(2 * x, 10))) for i, x in enumerate(reversed(d + [0])))) % 10) % 10
    n = "".join(map(str, d + [chk])); return " ".join(n[i:i+4] for i in range(0, 16, 4))
def id_doc(): return R.choice(["CA", "AY", "YA"]) + f"{R.randint(10000,99999)}" + R.choice("ABCDEFGHJKLM") + R.choice("ABCDEFGHJKLM")

